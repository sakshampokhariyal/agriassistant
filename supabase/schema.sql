-- AgriSahaya – Supabase schema
-- Paste the whole file into Supabase → SQL Editor → New query → Run.
-- Safe to run more than once (IF NOT EXISTS / OR REPLACE / DROP POLICY IF EXISTS).
--
-- Security model: every row belongs to one signed-in user (auth.uid()).
-- The browser uses the public publishable/anon key, so Row Level Security is what keeps
-- each farmer's data private: a user can read and change only their own rows, and
-- signed-out visitors can read nothing.

-- ───────────────────────── profiles ─────────────────────────
create table if not exists public.profiles (
  id            uuid primary key references auth.users (id) on delete cascade,
  phone         text,
  full_name     text,
  state         text,
  district      text,
  village       text,
  location_lat  double precision,
  location_lng  double precision,
  farm          jsonb not null default '{}'::jsonb,   -- land size, soil, irrigation, language …
  updated_at    timestamptz not null default now()
);

-- ───────────────────────── user_crops ─────────────────────────
-- One row per field. `id` is generated by the app (works offline first, then syncs).
create table if not exists public.user_crops (
  id             text primary key,
  user_id        uuid not null references auth.users (id) on delete cascade,
  crop_name      text not null,                       -- crop key, e.g. 'ragi', 'wheat', 'coconut'
  sowing_date    date not null,                       -- planting / transplanting date for some crops
  acreage        numeric(10, 2) not null default 0 check (acreage >= 0),
  current_stage  text,                                -- stage key at last sync, e.g. 'tillering'
  details        jsonb not null default '{}'::jsonb,  -- field name/number, variety, soil, irrigation, health
  created_at     timestamptz not null default now()
);
create index if not exists user_crops_user_idx on public.user_crops (user_id);

-- ───────────────────────── completed_tasks ─────────────────────────
-- Crop-calendar tasks the farmer ticked off.
create table if not exists public.completed_tasks (
  id            uuid primary key default gen_random_uuid(),
  user_id       uuid not null references auth.users (id) on delete cascade,
  crop_id       text not null references public.user_crops (id) on delete cascade,
  task_id       text not null,                        -- schedule task key, e.g. 'cri', 'harvest', 'preFert@2026'
  task_title    text,
  completed_at  timestamptz not null default now(),
  unique (user_id, crop_id, task_id)
);
create index if not exists completed_tasks_user_idx on public.completed_tasks (user_id);

-- ───────────────────────── Row Level Security ─────────────────────────
alter table public.profiles        enable row level security;
alter table public.user_crops      enable row level security;
alter table public.completed_tasks enable row level security;

-- Belt and braces: signed-out visitors (the public `anon` role used by the browser key)
-- get no table access at all; signed-in users get access, then limited to their own rows by RLS.
revoke all on public.profiles, public.user_crops, public.completed_tasks from anon;
grant select, insert, update, delete on public.profiles, public.user_crops, public.completed_tasks to authenticated;

-- Every policy below is `to authenticated` and checks auth.uid() against the row owner:
--   profiles.id (the profile row's id IS the user's id) · user_crops.user_id · completed_tasks.user_id

-- profiles: a user sees and edits only their own profile
drop policy if exists "profiles: own select" on public.profiles;
drop policy if exists "profiles: own insert" on public.profiles;
drop policy if exists "profiles: own update" on public.profiles;
drop policy if exists "profiles: own delete" on public.profiles;
create policy "profiles: own select" on public.profiles for select to authenticated using (auth.uid() = id);
create policy "profiles: own insert" on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "profiles: own update" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
create policy "profiles: own delete" on public.profiles for delete to authenticated using (auth.uid() = id);

-- user_crops: a user manages only their own fields
drop policy if exists "user_crops: own select" on public.user_crops;
drop policy if exists "user_crops: own insert" on public.user_crops;
drop policy if exists "user_crops: own update" on public.user_crops;
drop policy if exists "user_crops: own delete" on public.user_crops;
create policy "user_crops: own select" on public.user_crops for select to authenticated using (auth.uid() = user_id);
create policy "user_crops: own insert" on public.user_crops for insert to authenticated with check (auth.uid() = user_id);
create policy "user_crops: own update" on public.user_crops for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "user_crops: own delete" on public.user_crops for delete to authenticated using (auth.uid() = user_id);

-- completed_tasks: a user manages only their own ticks
drop policy if exists "completed_tasks: own select" on public.completed_tasks;
drop policy if exists "completed_tasks: own insert" on public.completed_tasks;
drop policy if exists "completed_tasks: own update" on public.completed_tasks;
drop policy if exists "completed_tasks: own delete" on public.completed_tasks;
create policy "completed_tasks: own select" on public.completed_tasks for select to authenticated using (auth.uid() = user_id);
create policy "completed_tasks: own insert" on public.completed_tasks for insert to authenticated with check (auth.uid() = user_id);
create policy "completed_tasks: own update" on public.completed_tasks for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "completed_tasks: own delete" on public.completed_tasks for delete to authenticated using (auth.uid() = user_id);

-- ───────────────────────── Auto-create a profile on sign-up ─────────────────────────
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, phone)
  values (new.id, new.phone)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Keep updated_at current on every profile change.
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at
  before update on public.profiles
  for each row execute function public.touch_updated_at();
